class WorkOrder(db.Model):
    """工单任务主表"""
    __tablename__ = 'work_orders'
    
    id = db.Column(db.Integer, primary_key=True, autoincrement=True)
    title = db.Column(db.String(255), nullable=False)
    description = db.Column(db.Text)
    type_id = db.Column(db.Integer, db.ForeignKey('dict_task_type.id'), nullable=False)
    priority_id = db.Column(db.Integer, db.ForeignKey('dict_priority.id'), nullable=False)
    status_id = db.Column(db.Integer, db.ForeignKey('dict_status.id'), nullable=False)
    creator_id = db.Column(db.Integer, db.ForeignKey('users.id'), nullable=False)
    assignee_id = db.Column(db.Integer, db.ForeignKey('users.id'), nullable=False)
    shop_id = db.Column(db.Integer, db.ForeignKey('shops.id'), nullable=False)
    due_date = db.Column(db.DateTime, nullable=False)
    completion_notes = db.Column(db.Text)
    completion_progress = db.Column(db.SmallInteger, default=0)  # 0-100
    created_at = db.Column(db.DateTime, default=datetime.utcnow)
    updated_at = db.Column(db.DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)
    
    # 关系
    comments = db.relationship('TaskComment', backref='work_order', lazy='dynamic', cascade='all, delete-orphan')
    attachments = db.relationship('TaskAttachment', backref='work_order', lazy='dynamic', cascade='all, delete-orphan')
    
    def to_dict(self, include_details=False):
        """转换为字典"""
        data = {
            'id': self.id,
            'title': self.title,
            'description': self.description,
            'type': self.task_type.to_dict() if self.task_type else None,
            'priority': self.priority.to_dict() if self.priority else None,
            'status': self.status.to_dict() if self.status else None,
            'creator': {
                'id': self.creator.id,
                'real_name': self.creator.real_name
            } if self.creator else None,
            'assignee': {
                'id': self.assignee.id,
                'real_name': self.assignee.real_name
            } if self.assignee else None,
            'shop': self.shop.to_dict() if self.shop else None,
            'due_date': self.due_date.isoformat() if self.due_date else None,
            'completion_progress': self.completion_progress,
            'created_at': self.created_at.isoformat() if self.created_at else None,
            'updated_at': self.updated_at.isoformat() if self.updated_at else None,
        }
        
        if include_details:
            data['completion_notes'] = self.completion_notes
            data['comments'] = [c.to_dict() for c in self.comments.order_by(TaskComment.created_at.desc()).all()]
            data['attachments'] = [a.to_dict() for a in self.attachments.all()]
        
        return data


