class ActivityLog(db.Model):
    """活动日志表 - 记录系统中的各种操作"""
    __tablename__ = 'activity_logs'
    
    id = db.Column(db.Integer, primary_key=True, autoincrement=True)
    action_type = db.Column(db.Enum(
        'work_order_created',      # 工单创建
        'work_order_status_changed',  # 工单状态变更
        'work_order_assigned',     # 工单分配
        'work_order_comment',      # 工单评论
        'work_order_image_added',  # 工单图片添加
        name='activity_type'
    ), nullable=False)
    work_order_id = db.Column(db.Integer, db.ForeignKey('work_orders.id'), nullable=True)
    user_id = db.Column(db.Integer, db.ForeignKey('users.id'), nullable=False)  # 执行操作的用户
    target_user_id = db.Column(db.Integer, db.ForeignKey('users.id'), nullable=True)  # 目标用户（如分配给谁）
    old_value = db.Column(db.String(100), nullable=True)  # 旧值（如状态变更前）
    new_value = db.Column(db.String(100), nullable=True)  # 新值（如状态变更后）
    comment = db.Column(db.Text, nullable=True)  # 备注/评论内容
    created_at = db.Column(db.DateTime, default=datetime.utcnow, index=True)
    
    # 关系
    work_order = db.relationship('WorkOrder', backref='activity_logs')
    user = db.relationship('User', foreign_keys=[user_id], backref='actions')
    target_user = db.relationship('User', foreign_keys=[target_user_id])
    
    def to_dict(self):
        """转换为字典"""
        # 构建活动描述
        description = self._build_description()
        
        return {
            'id': self.id,
            'action_type': self.action_type,
            'work_order_id': self.work_order_id,
            'work_order_title': self.work_order.title if self.work_order else None,
            'user_id': self.user_id,
            'user_name': self.user.real_name if self.user else None,
            'target_user_id': self.target_user_id,
            'target_user_name': self.target_user.real_name if self.target_user else None,
            'old_value': self.old_value,
            'new_value': self.new_value,
            'comment': self.comment,
            'description': description,
            'created_at': self.created_at.isoformat() if self.created_at else None
        }
    
    def _build_description(self):
        """构建活动描述文本"""
        user_name = self.user.real_name if self.user else '未知用户'
        
        if self.action_type == 'work_order_created':
            return f'{user_name} 创建了工单'
        elif self.action_type == 'work_order_status_changed':
            return f'{user_name} 将状态从 {self.old_value} 改为 {self.new_value}'
        elif self.action_type == 'work_order_assigned':
            target_name = self.target_user.real_name if self.target_user else '未知用户'
            return f'{user_name} 将工单分配给 {target_name}'
        elif self.action_type == 'work_order_comment':
            return f'{user_name} 添加了评论'
        elif self.action_type == 'work_order_image_added':
            return f'{user_name} 上传了图片'
        else:
            return f'{user_name} 执行了操作'


